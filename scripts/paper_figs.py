"""D1: write the pgfplots figures of paper V2 from the result JSON files. No number is typed by hand.

Usage: python scripts/paper_figs.py [--json results/paper_json/logs] [--out docs/paper_v2/figs]
fig_law: L1, the information added by the reader against log10(1 + earlier purchases of the target), six evidence bins
         per setting, 9B reader (mean of three seeds), development users (v40_law.json).
fig_forecast: L2, frozen forecast with its 80% interval against the observed gain, nine unseen scenarios (l2b_score.json).
The L4 stream is shown as a table only: its weekly series have very different lengths (Steam has two weeks).
"""
import argparse, json, pathlib

NAME = {"vg": "Video Games", "mi": "Musical Instr.", "steam": "Steam", "ind": "Industrial and Sci.",
        "ml1m": "ML-1M", "ml1m_plus": "ML-1M enr.", "cds": "CDs", "toys": "Toys", "sw": "Software", "baby": "Baby",
        "pet": "Pet", "groc": "Grocery", "arts": "Arts", "ml32m": "ML-32M", "mind": "MIND"}
# Label anchors chosen so that the names of the five close points of the lower left do not overlap.
ANCHOR = {"ml32m": "north east", "mind": "west", "sw": "south east", "pet": "north west", "baby": "west"}
STYLE = {"vg": "blue!70!black, mark=*", "mi": "orange!85!black, mark=square*", "steam": "green!50!black, mark=triangle*",
         "ind": "red!70!black, mark=diamond*", "ml1m": "gray, mark=o, dashed", "ml1m_plus": "gray!60, mark=x, dashed"}


def fig_law(root, out):
    L = json.loads((root / "v40_law.json").read_text())["law"]["9b-mean"]
    plots = []
    for k in ("vg", "mi", "steam", "ind", "ml1m", "ml1m_plus"):
        pts = " ".join(f"({x:.3f},{g:.4f})" for x, g, n in L[k]["bins"])
        plots.append(f"\\addplot[{STYLE[k]}, thick, mark size=1.6pt] coordinates {{{pts}}};\n\\addlegendentry{{{NAME[k]} (slope ${L[k]['slope']:+.3f}$)}}")
    tex = r"""\begin{tikzpicture}
\begin{axis}[width=0.92\linewidth, height=6.2cm, xlabel={$\log_{10}(1+n(t))$, earlier purchases of the target},
  ylabel={information added (nats)}, ymajorgrids, grid style={gray!20}, legend style={font=\footnotesize, draw=none, at={(0.5,-0.22)}, anchor=north, legend columns=3}, tick label style={font=\footnotesize}, label style={font=\small}]
\addplot[black!40, dotted, forget plot] coordinates {(0,0) (4,0)};
""" + "\n".join(plots) + "\n\\end{axis}\n\\end{tikzpicture}\n"
    (out / "fig_law.tex").write_text("% generated by scripts/paper_figs.py from v40_law.json; do not edit\n" + tex)


def fig_forecast(root, out):
    S = json.loads((root / "l2b_score.json").read_text())["scenarios"]
    rows, labels = [], []
    for k, v in S.items():
        lo, hi = v["m4_interval80"]
        rows.append(f"{v['observed']:.4f} {v['m4']:.4f} {v['m4'] - lo:.4f} {hi - v['m4']:.4f} {1 if v['inside'] else 0}")
        labels.append(f"\\node[font=\\scriptsize, anchor={ANCHOR.get(k, 'west')}, inner sep=2pt] at (axis cs:{v['observed']:.4f},{v['m4']:.4f}) {{{NAME[k]}}};")
    top = max(max(v["observed"], v["m4_interval80"][1]) for v in S.values()) * 1.1
    tex = r"""\begin{tikzpicture}
\begin{axis}[width=0.7\linewidth, height=6.2cm, xmin=0, ymin=0, xmax=""" + f"{top:.3f}" + r""", ymax=""" + f"{top:.3f}" + r""",
  xlabel={observed gain (nats)}, ylabel={frozen forecast (nats)}, ymajorgrids, xmajorgrids, grid style={gray!20},
  tick label style={font=\footnotesize}, label style={font=\small}, scaled ticks=false,
  xticklabel style={/pgf/number format/fixed}, yticklabel style={/pgf/number format/fixed}, clip=false]
\addplot[black!50, dashed, domain=0:""" + f"{top:.3f}" + r"""] {x};
\addplot[only marks, mark=*, mark size=1.8pt, blue!70!black, error bars/.cd, y dir=both, y explicit]
  table[x index=0, y index=1, y error minus index=2, y error plus index=3, row sep=\\] {""" + r" \\ ".join(rows) + r""" \\};
""" + "\n".join(labels) + "\n\\end{axis}\n\\end{tikzpicture}\n"
    (out / "fig_forecast.tex").write_text("% generated by scripts/paper_figs.py from l2b_score.json; do not edit\n" + tex)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default="results/paper_json/logs")
    ap.add_argument("--out", default="docs/paper_v2/figs")
    a = ap.parse_args()
    root, out = pathlib.Path(a.json) / "probe", pathlib.Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for f in (fig_law, fig_forecast):
        f(root, out)
        print("wrote", f.__name__)
