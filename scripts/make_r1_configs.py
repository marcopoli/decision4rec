"""R1+ configs (docs/11 version 2, Section 2): the development rtm configs with the reserved users.

F1: configs/small/<d>_r1rtm.yaml from <d>_rtm.yaml; F2: <d>_cold_r1rtm.yaml from <d>_cold_rtm.yaml. Only the name, the
eval users and the arms change (retriever and rtm), so first stages, pool, prompt and statements stay the development ones.
Run folders become runs/small/<d>/<d>_r1rtm_<tag>, read by scripts/r1_score.py (conf r1rtm). Writes files only.

    python scripts/make_r1_configs.py
"""
import yaml

FOUR = ("vg", "mi", "steam", "ind")
for src, dst in [(f"{d}_rtm", f"{d}_r1rtm") for d in FOUR] + [(f"{d}_cold_rtm", f"{d}_cold_r1rtm") for d in FOUR]:
    cfg = yaml.safe_load(open(f"configs/small/{src}.yaml"))
    cfg["name"] = dst
    cfg["eval"] = {**cfg["eval"], "users": "reserved", "n_test": 10000, "n_valid": 1000, "seed": 13}
    cfg["arms"] = [a for a in cfg["arms"] if a["name"] in ("retriever", "rtm")]
    assert [a["name"] for a in cfg["arms"]] == ["retriever", "rtm"], src
    with open(f"configs/small/{dst}.yaml", "w") as f:
        f.write(f"# R1+ (docs/11 v2): {src} with the reserved users. Generated by scripts/make_r1_configs.py; do not edit.\n")
        yaml.safe_dump(cfg, f, sort_keys=False)
    print(dst, cfg["eval"])
