def t_size_nats(root, out):
    """V26: information the reader adds to the list (nats per choice), by size. One record set per block."""
    n = load(root, "v26_nats")["nats"]
    def row(tag, label):
        m = n[tag]
        cells = []
        for k in DOM6:
            v = m[k]; lo, hi = v["ci"]
            cells.append(f"{v['added']+0.0:.3f}".replace("-0.000", "0.000") + ("^{\\ast}" if lo > 0 or hi < 0 else ""))
        return label + " & " + " & ".join(f"${c}$" for c in cells) + f" & ${m['mean_added']:.3f}$ \\\\"
    blocks = [("Same 8,000 records", [("rtm:kev-0.8b-rtm8k", "0.8B"), ("rtm:kev-4b-rtm8k", "4B"), ("rtm:kev-9b-rtm8k", "9B"), ("rtm:kev-27b-rtm8k", "27B")]),
              ("All 34,667 records", [("rtm:kev-0.8b-rtm", "0.8B"), ("rtm:kev-4b-rtm", "4B"), ("rtm:kev-9b-rtm", "9B")])]
    body = []
    for title, rs in blocks:
        body.append(f"\\addlinespace\n\\multicolumn{{8}}{{@{{}}l}}{{\\emph{{{title}}}}} \\\\")
        body += [row(t, l) for t, l in rs]
    users = " & ".join(f"{n['rtm:kev-9b-rtm'][k]['n']:,}" for k in DOM6)
    tex = r"""\begin{tabular}{@{}lrrrrrrr@{}}
\toprule
Decision model & """ + " & ".join(NAME[k] for k in DOM6) + r""" & Mean \\
Users with target in the 30 & """ + users + r""" & \\
\midrule
""" + "\n".join(body).replace("\\addlinespace\n", "", 1) + "\n\\bottomrule\n\\end{tabular}\n"
    write(out, "t_size_nats", "v26_nats.json", tex)


