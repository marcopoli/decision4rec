"""D1: write the tables of paper V2 from the result JSON files (docs/09). No number is typed by hand.

Usage: python scripts/paper_tables.py [--json results/paper_json/logs] [--out docs/paper_v2/tables]
Each table is one function that reads its JSON and writes tables/<name>.tex; the paper \\input{}s it.
Style (docs/paper style memory): one number per cell, arrows on metrics, exact variant names, Holm marks.
"""
import argparse, json, pathlib

NAME = {"vg": "Video Games", "mi": "Musical Instr.", "steam": "Steam", "ind": "Industrial and Sci.",
        "cds": "CDs and Vinyl", "toys": "Toys and Games", "sw": "Software"}
for k in list(NAME):
    NAME[k + "_cold"] = NAME[k]
REF = {"sasrecf+": "SASRecF+", "sasrecf": "SASRecF", "sasrec": "SASRec", "seqrules": "SeqRules"}


def load(root, name):
    return json.loads((root / f"{name}.json").read_text())


def pct(x):
    return f"${x:+.1f}\\%$"


def mark(holm):
    """Holm-corrected marks: * < .05, ** < .01."""
    return "^{\\ast\\ast}" if holm < 0.01 else "^{\\ast}" if holm < 0.05 else ""


def cell(c):
    return f"${c['rel']:+.1f}\\%{mark(c['holm'])}$"


def t_confirm(root, out):
    """Table 1: confirmation on reserved users, three Holm families (F1 leave-last-out, F2 cold, F3 unseen)."""
    rows = []
    label = {"f1": "F1, reserved users", "f2": "F2, cold items", "f3": "F3, unseen scenarios"}
    for f in ("r1_f1", "r1_f2", "r1_f3"):
        d = load(root, f)
        rows.append(f"\\addlinespace\n\\multicolumn{{7}}{{@{{}}l}}{{\\emph{{{label[d['family']]}}}}} \\\\")
        for k, v in d["domains"].items():
            rows.append(f"{NAME[k]} & {v['users']:,} & {REF[v['ref']]} & {v['ref_ndcg']:.4f} & {v['full']:.4f} & "
                        f"{cell(v['vs_ref'])} & {cell(v['vs_list'])} \\\\")
    tex = r"""\begin{tabular}{@{}lrlrrrr@{}}
\toprule
Scenario & Users & Reference & \multicolumn{1}{c}{Ref.\ NDCG@10\hb{}} & \multicolumn{1}{c}{\fullsys{}\hb{}} & vs reference\hb{} & vs \listsys{}\hb{} \\
\midrule""" + "\n" + "\n".join(rows).replace("\\addlinespace\n", "", 1) + "\n\\bottomrule\n\\end{tabular}\n"
    (out / "t_confirm.tex").write_text("% generated by scripts/paper_tables.py from r1_f1/f2/f3.json; do not edit\n" + tex)


